"""Build MSB-first static mascot and Latin-1 glyphs; Pillow is a build-time tool only."""
from pathlib import Path
import argparse
from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parent
parser = argparse.ArgumentParser()
parser.add_argument('--font', default='C:/Windows/Fonts/DejaVuSans.ttf')
args = parser.parse_args()
out = ['// Generated by generate_ui_assets.py. DejaVu Sans (Bitstream Vera license).',
       '#pragma once', '#include <Arduino.h>',
       'struct UiGlyph { uint16_t code, offset; uint8_t width; };']
mascot = (root.parent / 'preview/handoff/mono/mascot.bin').read_bytes()
assert len(mascot) == 5454
out.append('static const uint8_t uiMascot[] PROGMEM = {' + ','.join(map(str, mascot)) + '};')
for size in (12, 18, 40):
    font = ImageFont.truetype(args.font, size)
    data, glyphs = [], []
    for code in list(range(32, 127)) + list(range(160, 256)) + [8230]:
        width = max(1, round(font.getlength(chr(code))))
        im = Image.new('1', (width, size + 4))
        ImageDraw.Draw(im).text((0, 0), chr(code), font=font, fill=1)
        glyphs.append((code, len(data), width))
        for y in range(im.height):
            for x in range(0, width, 8):
                data.append(sum((128 >> b) for b in range(8) if x+b < width and im.getpixel((x+b,y))))
    out.append(f'static const uint8_t uiFont{size}[] PROGMEM = {{'+','.join(map(str,data))+'};')
    out.append(f'static const UiGlyph uiGlyph{size}[] PROGMEM = {{'+','.join('{%d,%d,%d}'%g for g in glyphs)+'};')
(root/'src/ui_assets.h').write_text('\n'.join(out)+'\n', encoding='utf-8')
